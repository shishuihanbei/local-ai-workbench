function tabNameFromHash() {
  const name = location.hash.replace(/^#/, "");
  return TITLES[name] ? name : "";
}

function initialTab() {
  return tabNameFromHash() || "overview";
}

function rememberTab(name) {
  const hash = "#" + name;
  if (location.hash !== hash) history.replaceState(null, "", hash);
}

